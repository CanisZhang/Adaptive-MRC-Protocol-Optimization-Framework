function maxb = OGSEbmax(frequency, N)
    OGSEdelta = N * 1000 / frequency;  
    gmax = 30e-5;
    pulse_tcos = mati.DiffusionPulseSequence(1, ...
        'TE', 150, ...              
        'delta', OGSEdelta, ...    
        'Delta', OGSEdelta + 7, ... 
        'G', [gmax], ...         
        'n', N * ones(1, 1), ...   
        'shape', "tcos", ...        
        'gdir', [0 0 0], ...       
        'trise', 1.54);            
    maxb = 1000*pulse_tcos.b(1);
end
